def main():
    with open("src/data/characters.json", "r", encoding="utf-8") as f:
        chars = json.load(f)

    by_hanzi = {c["hanzi"] for c in chars}

    all_components = set()
    for c in chars:
        for comp in c.get("components") or []:
            all_components.add(comp)
        rad = c.get("radical")
        if rad and rad != c["hanzi"]:
            all_components.add(rad)

    missing = all_components - by_hanzi
    added = 0

    for comp in sorted(missing):
        name = RADICAL_NAMES.get(comp, "")
        if not name:
            continue
        chars.append(
            {
                "hanzi": comp,
                "pinyin": "",
                "level": 0,
                "freq": 0,
                "meaningPrimary": name,
                "meaningsRu": [name],
                "meaningsEn": [name],
                "hasStrokes": False,
            }
        )
        added += 1

    with open("src/data/characters.json", "w", encoding="utf-8") as f:
        json.dump(chars, f, ensure_ascii=False, indent=None)

    still_missing = (all_components - by_hanzi) - set(RADICAL_NAMES.keys())
    print(f"Added {added} radical entries")
    print(f"Still unnamed: {len(still_missing)}")


if __name__ == "__main__":
    main()
