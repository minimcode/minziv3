def translate_meaning(hanzi: str, en_meanings: list[str], primary: str) -> str:
    """Translate an English CEDICT meaning to Russian."""
    # Check hanzi-specific overrides first
    if hanzi in HANZI_OVERRIDES:
        return HANZI_OVERRIDES[hanzi]

    # Try the primary meaning
    first_en = (en_meanings[0] if en_meanings else primary).strip()

    # Clean CEDICT cruft
    clean = re.sub(r"\s*\([^)]*\)\s*", " ", first_en).strip()
    clean = re.sub(r"\s*\[[^\]]*\]\s*", " ", clean).strip()

    # Try exact match on first clause
    first_clause = clean.split(";")[0].strip()
    first_clause_lower = first_clause.lower()

    if first_clause_lower in EN_RU:
        return EN_RU[first_clause_lower]

    # Try matching with "to " prefix stripped for verbs
    if first_clause_lower.startswith("to "):
        verb_key = first_clause_lower
        if verb_key in EN_RU:
            return EN_RU[verb_key]
        # Try without "to "
        bare = first_clause_lower[3:].strip()
        if bare in EN_RU:
            return EN_RU[bare]

    # Try first word
    first_word = first_clause_lower.split()[0] if first_clause_lower else ""
    if first_word in EN_RU:
        return EN_RU[first_word]

    # Try CEDICT patterns
    for pat, ru in CEDICT_PATTERNS:
        if re.search(pat, first_en, re.I):
            return ru

    # If meaningPrimary already has Cyrillic
    if primary and re.search(r"[\u0400-\u04FF]", primary):
        return primary

    return ""


def main():
    with open("src/data/characters.json", "r", encoding="utf-8") as f:
        chars = json.load(f)

    translated = 0
    still_missing = 0

    for c in chars:
        has_ru = c.get("meaningsRu") and len(c["meaningsRu"]) > 0 and c["meaningsRu"][0]
        if has_ru:
            continue

        ru = translate_meaning(
            c["hanzi"],
            c.get("meaningsEn", []),
            c.get("meaningPrimary", ""),
        )

        if ru:
            c["meaningsRu"] = [ru]
            c["meaningPrimary"] = ru
            translated += 1
        else:
            still_missing += 1

    with open("src/data/characters.json", "w", encoding="utf-8") as f:
        json.dump(chars, f, ensure_ascii=False, indent=None)

    print(f"Translated: {translated}")
    print(f"Still missing: {still_missing}")

    # Show some still-missing ones
    missing = [c for c in chars if not (c.get("meaningsRu") and c["meaningsRu"][0])]
    for c in missing[:20]:
        en = c.get("meaningsEn", [""])[0][:60]
        print(f"  {c['hanzi']} {c['pinyin']} L{c['level']}: {en}")


if __name__ == "__main__":
    main()
